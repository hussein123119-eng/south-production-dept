const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const BACKUPS_DIR = path.join(ROOT, 'backups');

function copyDir(src, dest) {
  if (!fs.existsSync(dest)) fs.mkdirSync(dest, { recursive: true });
  fs.readdirSync(src).forEach(item => {
    const s = path.join(src, item);
    const d = path.join(dest, item);
    if (fs.statSync(s).isDirectory()) {
      if (item !== 'node_modules' && item !== 'backups' && item !== '.git') copyDir(s, d);
    } else {
      fs.copyFileSync(s, d);
    }
  });
}


function saveVersion(v) {
  const versionStr = v.startsWith('v') ? v : 'v' + v;
  const target = path.join(BACKUPS_DIR, 'version_' + versionStr);
  if (!fs.existsSync(target)) fs.mkdirSync(target, { recursive: true });
  copyDir(path.join(ROOT, 'js'), path.join(target, 'js'));
  copyDir(path.join(ROOT, 'css'), path.join(target, 'css'));
  fs.copyFileSync(path.join(ROOT, 'index.html'), path.join(target, 'index.html'));
  console.log('✄ Snapshot ' + versionStr + ' saved to backups!');
}

function restoreVersion(v) {
  const versionStr = v.startsWith('v') ? v : 'v' + v;
  const target = path.join(BACKUPS_DIR, 'version_' + versionStr);
  if (!fs.existsSync(target)) {
    console.error('❌ Version ' + versionStr + ' does not exist in backups!');
    return false;
  }
  copyDir(path.join(target, 'js'), path.join(ROOT, 'js'));
  copyDir(path.join(target, 'css'), path.join(ROOT, 'css'));
  fs.copyFileSync(path.join(target, 'index.html'), path.join(ROOT, 'index.html'));
  console.log('✄ Codebase successfully restored to ' + versionStr + '!');
  return true;
}

function setupCloudFiles() {
  const firebaseJson = {
    hosting: {
      public: '.',
      ignore: ['firebase.json', '**/.*', '**/node_modules/**', 'database/backups/**', 'tools/**', 'backend/**'],
      rewrites: [{ source: '**', destination: '/index.html' }]
    }
  };
  fs.writeFileSync(path.join(ROOT, 'firebase.json'), JSON.stringify(firebaseJson, null, 2), 'utf8');

  const firebaseRc = { projects: { default: 'south-production-dept' } };
  fs.writeFileSync(path.join(ROOT, '.firebaserc'), JSON.stringify(firebaseRc, null, 2), 'utf8');

  const dockerLines = [
    'FROM node:20-alpine',
    'WORKDIR /app',
    'COPY package*.json ./',
    'COPY . .',
    'EXPOSE 3000',
    'ENV PORT=3000',
    'ENV NODE_ENV=production',
    'CMD ["node", "server.js"]'
  ];
  fs.writeFileSync(path.join(ROOT, 'Dockerfile'), dockerLines.join('\n') + '\n', 'utf8');

  const dockerIgnoreLines = ['node_modules', '.git', '.vscode', 'backups', 'database/backups'];
  fs.writeFileSync(path.join(ROOT, '.dockerignore'), dockerIgnoreLines.join('\n') + '\n', 'utf8');

  console.log('✅ Firebase and Google Cloud Run deployment configuration files generated successfully!');
}

